/**
 * Turns the Expo web export in dist/ into an installable, offline web app:
 * fills in the base path, writes the web app manifest and the service worker
 * with a precache list, and adds the files GitHub Pages needs.
 */
const crypto = require('crypto');
const fs = require('fs');
const path = require('path');

const brand = require('../src/config/brand.json');

const root = path.resolve(__dirname, '..');
const dist = path.join(root, process.argv[2] || 'dist');
const base = (process.env.WEB_BASE_URL || '').replace(/\/+$/, '');

if (!fs.existsSync(path.join(dist, 'index.html'))) {
  console.error(`No web export found in ${dist}. Run expo export --platform web first.`);
  process.exit(1);
}

function walk(directory) {
  const files = [];
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const full = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else files.push(full);
  }
  return files;
}

// 1. Base path placeholders in the HTML shell, plus a 404 copy for deep links on GitHub Pages.
const indexPath = path.join(dist, 'index.html');
const html = fs.readFileSync(indexPath, 'utf8').replace(/%BASE_URL%/g, base);
fs.writeFileSync(indexPath, html);
fs.writeFileSync(path.join(dist, '404.html'), html);
fs.writeFileSync(path.join(dist, '.nojekyll'), '');

// 2. Web app manifest.
const manifest = {
  name: brand.name,
  short_name: 'Ledger',
  description: 'Private two-currency spending tracker that works offline.',
  id: `${base}/`,
  start_url: `${base}/`,
  scope: `${base}/`,
  display: 'standalone',
  orientation: 'portrait',
  background_color: brand.colors.splashBackground,
  theme_color: brand.colors.splashBackground,
  icons: [
    { src: `${base}/icons/icon-192.png`, sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: `${base}/icons/icon-512.png`, sizes: '512x512', type: 'image/png', purpose: 'any' },
    {
      src: `${base}/icons/icon-maskable-512.png`,
      sizes: '512x512',
      type: 'image/png',
      purpose: 'maskable',
    },
  ],
};
fs.writeFileSync(path.join(dist, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

// 3. Service worker that precaches the whole app for offline use.
const skip = (relative) =>
  relative === 'sw.js' ||
  relative === '404.html' ||
  relative === '.nojekyll' ||
  relative.endsWith('.map') ||
  relative.startsWith('reminders/');
const files = walk(dist)
  .map((file) => path.relative(dist, file).split(path.sep).join('/'))
  .filter((relative) => !skip(relative))
  .sort();
const hash = crypto.createHash('sha256');
for (const relative of files) {
  hash.update(relative);
  hash.update(fs.readFileSync(path.join(dist, relative)));
}
const version = hash.digest('hex').slice(0, 12);
const precache = files.map((relative) => `${base}/${relative}`);
precache.unshift(`${base}/`);

const worker = `/* Pocket Ledger service worker, version ${version}. Generated by scripts/build-pwa.js. */
const VERSION = ${JSON.stringify(version)};
const SHELL_CACHE = 'pocket-ledger-shell-' + VERSION;
const BASE = ${JSON.stringify(base)};
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(SHELL_CACHE).then((cache) => cache.addAll(PRECACHE)).then(() => self.skipWaiting()),
  );
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith('pocket-ledger-shell-') && key !== SHELL_CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || !url.pathname.startsWith(BASE + '/')) return;
  if (url.pathname.startsWith(BASE + '/reminders/')) return;

  if (request.mode === 'navigate') {
    // The app is a single page: every navigation is answered with the cached shell.
    event.respondWith(
      caches
        .match(BASE + '/index.html', { cacheName: SHELL_CACHE })
        .then((cached) => cached || fetch(request)),
    );
    return;
  }

  event.respondWith(
    caches.match(request, { cacheName: SHELL_CACHE, ignoreSearch: true }).then(
      (cached) =>
        cached ||
        fetch(request).then((response) => {
          if (response.ok && response.type === 'basic') {
            const copy = response.clone();
            caches.open(SHELL_CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        }),
    ),
  );
});
`;
fs.writeFileSync(path.join(dist, 'sw.js'), worker);

const totalBytes = files.reduce(
  (sum, relative) => sum + fs.statSync(path.join(dist, relative)).size,
  0,
);
console.log(
  `PWA ready: base "${base || '/'}", ${files.length} files precached (${(totalBytes / 1024 / 1024).toFixed(1)} MB), version ${version}`,
);
